class LatencyTracker:
    """Lightweight latency tracker."""
    def __init__(self):
        self.metrics = {}
        self._starts = {}

    def start(self, name):
        self._starts[name] = time.perf_counter()

    def stop(self, name):
        elapsed = time.perf_counter() - self._starts.pop(name, time.perf_counter())
        self.metrics.setdefault(name, []).append(elapsed)
        return elapsed

    def summary(self):
        for name, times in self.metrics.items():
            avg = sum(times) / len(times) * 1000
            logger.info(f'{name}: avg={avg:.2f} ms  count={len(times)}')


